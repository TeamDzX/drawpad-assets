"""
Silhouette outlines for the dot-to-dot packs.

Each entry is an ordered, closed path in normalised (0..1) coordinates with y
pointing down. The points ARE the dots, in connection order, so they are placed
by hand at the corners and inflections that make the subject readable — the
first version of these packs sampled points off a bounding box and the results
did not read as anything. `step` is the longest segment allowed before the
renderer subdivides it, which keeps dot spacing even without hand-placing every
intermediate point.

`details` are light-grey strokes drawn on top (eyes, windows, wheels). They are
deliberately NOT part of the numbered path — a child connects the black dots and
the grey marks finish the picture.
"""
import math

# --------------------------------------------------------------------------
# procedural builders
# --------------------------------------------------------------------------

def _poly(cx, cy, r, n, start_deg=-90, squash=1.0):
    pts = []
    for i in range(n):
        a = math.radians(start_deg + 360.0 * i / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a) * squash))
    return pts


def star(points=5, r_out=0.40, r_in=0.17, cx=0.5, cy=0.52):
    pts = []
    for i in range(points * 2):
        a = math.radians(-90 + 180.0 * i / points)
        r = r_out if i % 2 == 0 else r_in
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def heart(n=22, cx=0.5, cy=0.50, s=0.030):
    """Classic heart curve, sampled from the bottom tip clockwise."""
    pts = []
    for i in range(n):
        t = math.pi / 2 - 2 * math.pi * i / n     # start at the bottom point
        x = 16 * math.sin(t) ** 3
        y = (13 * math.cos(t) - 5 * math.cos(2 * t)
             - 2 * math.cos(3 * t) - math.cos(4 * t))
        pts.append((cx + s * x, cy - s * y))
    return pts


def flower(petals=6, n=24, cx=0.5, cy=0.50, r=0.38, depth=0.38):
    pts = []
    for i in range(n):
        a = 2 * math.pi * i / n - math.pi / 2
        rr = r * (1 - depth + depth * math.cos(petals * a))
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return pts


def _arc(cx, cy, r, a0, a1, n=18):
    """Points along a circular arc, degrees, screen coords (y down)."""
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / (n - 1.0))),
             cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / (n - 1.0))))
            for i in range(n)]


def _spiral(cx, cy, r0, r1, turns, n=64):
    """Archimedean spiral — a snail shell drawn as a polygon reads as a scribble."""
    return [[(cx + (r0 + (r1 - r0) * i / (n - 1.0)) *
              math.cos(2 * math.pi * turns * i / (n - 1.0)),
              cy + (r0 + (r1 - r0) * i / (n - 1.0)) *
              math.sin(2 * math.pi * turns * i / (n - 1.0)))
             for i in range(n)]]


def _circle_details(cx, cy, r, n=28):
    ring = _poly(cx, cy, r, n)
    return [ring + [ring[0]]]          # close on the start point, not a chord


